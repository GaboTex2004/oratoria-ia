"""Run real local models on explicitly identified synthetic fixtures; no microphone."""

import argparse
import base64
import json
import time
from pathlib import Path

from app.schemas.evaluation import SpeechEvaluationRequestSchema
from app.schemas.simulation import (
    SimulationFeedbackRequestSchema,
    SimulationHistoryMessageSchema,
    SimulationReplyRequestSchema,
)
from app.services.evaluation.evaluator import SpeechEvaluationService
from app.services.pose.analyzer import analyze_frames
from app.services.simulation.service import SimulationConversationService
from app.services.speech.analyzer import SpeechAnalysisService


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--audio", type=Path, required=True, help="WAV generated by New-SyntheticAudio.ps1")
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()
    results = {"fixtureType": "synthetic-windows-speech-and-blank-image", "checks": {}}
    args.output.parent.mkdir(parents=True, exist_ok=True)

    def check(name, action):
        started = time.monotonic()
        try:
            value = action()
            results["checks"][name] = {
                "ok": True,
                "elapsedSeconds": round(time.monotonic() - started, 2),
                "result": value.model_dump() if hasattr(value, "model_dump") else value,
            }
        except Exception as exc:
            results["checks"][name] = {
                "ok": False,
                "elapsedSeconds": round(time.monotonic() - started, 2),
                "error": str(exc),
                "type": type(exc).__name__,
            }
        args.output.write_text(json.dumps(results, ensure_ascii=False, indent=2), encoding="utf-8")

    check(
        "transcription",
        lambda: SpeechAnalysisService().analyze(
            "synthetic-local", args.audio.read_bytes(), "audio/wav", 21, "synthetic.wav"
        ),
    )
    speech = results["checks"]["transcription"]
    if speech["ok"]:
        check(
            "evaluation",
            lambda: SpeechEvaluationService().evaluate(
                SpeechEvaluationRequestSchema(
                    sessionId="synthetic-local",
                    trainingType="PRESENTATION",
                    transcriptText=speech["result"]["transcriptText"],
                    metrics=speech["result"]["metrics"],
                )
            ),
        )
    service = SimulationConversationService()
    request = SimulationReplyRequestSchema(
        simulationId="synthetic-sim",
        scenarioId="job-interview",
        trainingType="INTERVIEW",
        difficulty="BASIC",
        aiRole="reclutador",
        context="Entrevista laboral universitaria.",
        objective="Comunicar experiencia y resultados.",
        rules=["Una pregunta breve por turno."],
        history=[],
        userTranscript="Desarrollé una plataforma universitaria. Organicé las tareas y verificamos el registro de usuarios.",
        turnNumber=1,
        maxTurns=3,
    )
    check("simulation_reply", lambda: service.reply(request))
    check(
        "simulation_feedback",
        lambda: service.feedback(
            SimulationFeedbackRequestSchema(
                simulationId="synthetic-sim",
                scenarioId="job-interview",
                trainingType="INTERVIEW",
                difficulty="BASIC",
                context="Entrevista laboral universitaria.",
                objective="Explicar aportes y resultados.",
                history=[
                    SimulationHistoryMessageSchema(speaker="USER", text=request.userTranscript),
                    SimulationHistoryMessageSchema(speaker="AI", text="¿Cuál fue tu aporte?"),
                    SimulationHistoryMessageSchema(
                        speaker="USER",
                        text="Implementé la autenticación y pruebas. El equipo demostró el recorrido completo.",
                    ),
                ],
            )
        ),
    )
    import cv2
    import numpy as np

    _, image = cv2.imencode(".jpg", np.zeros((360, 480, 3), dtype=np.uint8))
    check("pose_blank_image", lambda: analyze_frames([base64.b64encode(image).decode()]))
    for name, value in results["checks"].items():
        print(name, "PASS" if value["ok"] else "FAIL", value["elapsedSeconds"])
    return 0 if all(value["ok"] for value in results["checks"].values()) else 1


if __name__ == "__main__":
    raise SystemExit(main())
